"""Evidence-based database intelligence reporting.

Generates database health, query optimization, index recommendation,
documentation, performance comparison, and anomaly investigation reports
in Markdown and JSON. PDF is supported only when an external renderer is
available; otherwise the JSON/Markdown output is the authoritative artifact.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any


@dataclass
class ReportSection:
    title: str
    content: str


@dataclass
class Report:
    """A generated report."""

    report_type: str
    database: str
    generated_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    sections: list[ReportSection] = field(default_factory=list)
    metadata: dict = field(default_factory=dict)

    def add_section(self, title: str, content: str) -> None:
        self.sections.append(ReportSection(title=title, content=content))

    def to_markdown(self) -> str:
        lines = [
            f"# {self.report_type} Report",
            f"**Database:** {self.database}",
            f"**Generated:** {self.generated_at}",
            "",
        ]
        for section in self.sections:
            lines.append(f"## {section.title}")
            lines.append(section.content)
            lines.append("")
        lines.append("---")
        lines.append("*Generated by QueryMind MCP. All values are evidence-based; unavailable metrics are noted.*")
        return "\n".join(lines)

    def to_json(self) -> dict:
        return {
            "report_type": self.report_type,
            "database": self.database,
            "generated_at": self.generated_at,
            "metadata": self.metadata,
            "sections": [
                {"title": s.title, "content": s.content} for s in self.sections
            ],
        }


class ReportingService:
    """Builds structured reports from analysis results."""

    def health_report(
        self, database: str, health_metrics: list[dict]
    ) -> Report:
        report = Report(report_type="database_health", database=database)
        lines = ["| Metric | Value | Status | Threshold | Unit |", "|---|---|---|---|---|"]
        for m in health_metrics:
            lines.append(
                f"| {m.get('name')} | {m.get('value')} | {m.get('status')} | "
                f"{m.get('threshold','-')} | {m.get('unit','')} |"
            )
        report.add_section("Health Metrics", "\n".join(lines))
        return report

    def optimization_report(
        self, database: str, findings: list[dict], recommendations: list[dict]
    ) -> Report:
        report = Report(report_type="query_optimization", database=database)
        lines = ["## Plan Findings", ""]
        if findings:
            for f in findings:
                lines.append(f"- **{f.get('identifier')}** ({f.get('severity')}): {f.get('explanation')}")
                lines.append(f"  - Suggested action: {f.get('suggested_action')}")
        else:
            lines.append("No significant plan findings.")
        lines.append("")
        lines.append("## Index Recommendations")
        if recommendations:
            for r in recommendations:
                lines.append(
                    f"- `{r.get('proposed_sql')}` — {r.get('reason')} "
                    f"(confidence: {r.get('confidence')})"
                )
        else:
            lines.append("No index recommendations.")
        report.add_section("Optimization Findings", "\n".join(lines))
        return report

    def anomaly_report(
        self, database: str, events: list[dict]
    ) -> Report:
        report = Report(report_type="anomaly_investigation", database=database)
        lines = ["| Event | Metric | Observed | Baseline | Score | Severity | Algorithm |", "|---|---|---|---|---|---|---|"]
        for e in events:
            lines.append(
                f"| {e.get('event_id')} | {e.get('metric')} | {e.get('observed_value')} | "
                f"{e.get('expected_baseline')} | {e.get('anomaly_score')} | "
                f"{e.get('severity')} | {e.get('detection_algorithm')} |"
            )
        report.add_section("Anomaly Events", "\n".join(lines))
        return report
